package catalog_test

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/autobrr/dashbrr/internal/services/catalog"
)

var update = flag.Bool("update", false, "rewrite web/src/types/serviceTypes.gen.ts")

const regenerate = "go test ./internal/services/catalog -run TestTypeScriptServiceTypes -update"

func TestTypeScriptServiceTypes(t *testing.T) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by `%s`. DO NOT EDIT.\n\n", regenerate)
	b.WriteString("export type CatalogServiceType =\n")
	for _, st := range catalog.All() {
		fmt.Fprintf(&b, "  | %q\n", st.Name)
	}
	got := strings.TrimSuffix(b.String(), "\n") + ";\n"

	path := filepath.Join("..", "..", "..", "web", "src", "types", "serviceTypes.gen.ts")
	if *update {
		if err := os.WriteFile(path, []byte(got), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if got != string(want) {
		t.Fatalf("web/src/types/serviceTypes.gen.ts does not match the service types in internal/services/catalog; run %s", regenerate)
	}
}
